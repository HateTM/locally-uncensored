#!/usr/bin/env node
// Regenerates src/lib/llama-architectures.ts from the llama.cpp revision that
// scripts/build-llama.sh pins. Run it after every LLAMA_TAG / LLAMA_COMMIT bump;
// src/lib/__tests__/llama-architectures.test.ts fails until it has been run.
//
//   node scripts/gen-llama-architectures.mjs
//
// It reads src/llama-arch.cpp at the pinned COMMIT (not the tag, same reason as
// build-llama.sh: a tag can move) and keeps the `{ LLM_ARCH_XXX, "name" }`
// pairs, the same pattern parseKnownArchitectures (src/api/gguf-arch.ts) uses.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const script = readFileSync(join(root, 'scripts/build-llama.sh'), 'utf8')
const tag = /LLAMA_TAG="\$\{LLAMA_TAG:-([^}"]+)\}"/.exec(script)?.[1]
const commit = /LLAMA_COMMIT="\$\{LLAMA_COMMIT:-([0-9a-f]{40})\}"/.exec(script)?.[1]
if (!tag || !commit) throw new Error('LLAMA_TAG / LLAMA_COMMIT not found in scripts/build-llama.sh')

const url = `https://raw.githubusercontent.com/ggml-org/llama.cpp/${commit}/src/llama-arch.cpp`
const res = await fetch(url)
if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
const source = await res.text()

const names = new Set()
const re = /\{\s*LLM_ARCH_[A-Z0-9_]+\s*,\s*"([^"]+)"\s*\}/g
for (let m; (m = re.exec(source)) !== null;) names.add(m[1])
if (names.size < 50) throw new Error(`only ${names.size} architectures parsed from ${url}, refusing to write`)

const list = [...names].sort()
const body = `// GENERATED by scripts/gen-llama-architectures.mjs, do not edit by hand.
//
// The GGUF architectures (general.architecture) the bundled LU Engine can load:
// every \`{ LLM_ARCH_*, "name" }\` in src/llama-arch.cpp of the llama.cpp revision
// scripts/build-llama.sh pins. Discover uses it to keep models the engine
// cannot open out of the live Hugging Face feed (see api/discover-trending.ts).

export const LLAMA_ARCH_TAG = '${tag}'
export const LLAMA_ARCH_COMMIT = '${commit}'

export const LLAMA_ARCHITECTURES: ReadonlySet<string> = new Set([
${list.map((n) => `  '${n}',`).join('\n')}
])
`
writeFileSync(join(root, 'src/lib/llama-architectures.ts'), body)
console.log(`wrote ${list.length} architectures for ${tag} (${commit.slice(0, 7)})`)
